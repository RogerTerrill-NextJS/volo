select is(jsonb_array_length(public.list_flight_outcomes(pg_temp.id(30))),1,'Cursor advances beyond current request');
select is(jsonb_array_length(public.list_flight_outcomes(pg_temp.id(31))),0,'Final cursor does not repeat earlier requests');
select is(public.save_flight_outcome(pg_temp.id(30),true,0)->>'code','saved','Owner confirms Yes');
create temporary table first_response as select public.get_flight_outcome(pg_temp.id(30)) value;
select is(public.save_flight_outcome(pg_temp.id(30),true,0)->'outcome',(select value from first_response),'Exact retry preserves revision/timestamp');
select pg_temp.actor(3);
select is(public.get_flight_outcome(pg_temp.id(30))->>'answer',null::text,'Requester cannot see owner answer');
select is(public.save_flight_outcome(pg_temp.id(30),true,0)->>'code','saved','Requester confirms independently');
select is(jsonb_array_length(public.list_flight_outcomes()),1,'Requester only sees own pair');
select is(public.get_flight_outcome(pg_temp.id(31)),null::jsonb,'Another accepted requester cannot read this pair');
select is(public.save_flight_outcome(pg_temp.id(31),true,0)->>'code','outcome_unavailable','Another requester cannot respond');
select throws_ok($$select * from public.flight_outcomes$$,'42501',null,'Raw rows denied to participants');
select throws_ok($$insert into public.flight_outcomes(request_id,respondent_id,flew_together) values(pg_temp.id(30),pg_temp.id(2),false)$$,'42501',null,'Cannot forge another respondent');
select pg_temp.actor(1);
select is(public.admin_mvp_metrics()->>'outcomeResponses','2','Two answers counted');
select is(public.admin_mvp_metrics()->>'confirmedConnections','1','Two Yes answers count one connection');
select is(public.admin_mvp_metrics()->>'bothParticipantsConfirmed','1','Both participants Yes distinguished');
select is(public.admin_mvp_metrics()->>'oneParticipantConfirmed','0','Both not counted as exactly one');
select is(public.get_flight_outcome(pg_temp.id(30)),null::jsonb,'Admin cannot inspect participant outcome');
select is(jsonb_array_length(public.list_flight_outcomes()),0,'Unrelated admin has no participant list');
select is(public.save_flight_outcome(pg_temp.id(30),false,0)->>'code','outcome_unavailable','Admin cannot answer for participant');
select pg_temp.actor(2);
select is(public.save_flight_outcome(pg_temp.id(30),false,1)->>'code','saved','Correction updates existing response');
select is(public.get_flight_outcome(pg_temp.id(30))->>'revision','2','Correction increments revision');
select is(public.save_flight_outcome(pg_temp.id(30),true,1)->>'code','stale','Stale differing correction cannot overwrite latest');
select is(public.save_flight_outcome(pg_temp.id(30),false,0)->>'code','saved','Identical stale retry confirms latest without writing');
select throws_ok($$select public.save_flight_outcome(pg_temp.id(30),null,2)$$,'22023',null,'Null answer denied');
select throws_ok($$select public.save_flight_outcome(pg_temp.id(30),true,-1)$$,'22023',null,'Invalid revision denied');
select pg_temp.actor(1);
select is(public.admin_mvp_metrics()->>'outcomeResponses','2','Correction never duplicates respondent');
select is(public.admin_mvp_metrics()->>'oneParticipantConfirmed','1','One Yes distinguished after correction');
select is(public.admin_mvp_metrics()->>'conflictingConnections','1','Yes/No conflict is explicit aggregate');
select is(public.admin_mvp_metrics()->>'bothParticipantsConfirmed','0','Both Yes decreases after correction');
select ok(public.admin_mvp_metrics()::text !~ 'Outcome pilot|22900000|KPAO','Metrics expose no identities, routes or answers');
select pg_temp.actor(3);
select is(public.get_flight_outcome(pg_temp.id(30))->>'answer','true','Requester still sees only own Yes');
select is(public.save_flight_outcome(pg_temp.id(30),false,1)->>'code','saved','Requester can also correct');
select pg_temp.actor(1);
select is(public.admin_mvp_metrics()->>'confirmedConnections','0','Two No answers do not confirm a connection');
reset role;
update public.flights set status='completed' where id=pg_temp.id(20);
set local role authenticated;
select pg_temp.actor(2);
select isnt(public.get_flight_outcome(pg_temp.id(30)),null::jsonb,'Completed accepted flight remains eligible');
select is(public.save_flight_outcome(pg_temp.id(31),true,0)->>'code','saved','Separate accepted request has independent outcome');
reset role;
