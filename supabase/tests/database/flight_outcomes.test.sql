-- persistence guard before any authenticated operation; production code is unchanged.
create function pg_temp.dateflight(stamp timestamptz,zone text default 'UTC') returns void language plpgsql as $$begin
 alter table public.flights disable trigger flights_prepare;
 update public.flights set departure_at=stamp,departure_timezone=zone,departure_local_date=(stamp at time zone zone)::date where id=pg_temp.id(20);
 alter table public.flights enable trigger flights_prepare;
end$$;
insert into auth.users(id,email) select pg_temp.id(n),'outcome-'||n||'@example.invalid' from generate_series(1,5)n;
insert into public.memberships(user_id,role) select pg_temp.id(n),case when n=1 then 'admin' else 'member' end::public.member_role from generate_series(1,5)n;
