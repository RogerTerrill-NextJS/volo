reset role;
select pg_temp.dateflight(now()-interval '2 days');
set local role authenticated;
select pg_temp.actor(2);
select is(public.get_flight_outcome(pg_temp.id(30))->>'revision','0','Eligible unresponded connection has revision zero');
select is(public.get_flight_outcome(pg_temp.id(30))->>'answer',null::text,'Unanswered is not No');
