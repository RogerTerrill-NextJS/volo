select is(public.get_flight_outcome(pg_temp.id(30)),null::jsonb,'Disabled counterpart fences pair');
select pg_temp.actor(1);
select is(public.admin_mvp_metrics()->>'confirmedConnections','1','Historical responses retained after audience/member closure');
reset role;
